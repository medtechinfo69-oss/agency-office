/* Isolated local test database ONLY. Never run against production: these tests
 * exercise destructive actions and password changes using test credentials.
 * Start backend on 8010 with a disposable DATA_DIR, DB_PATH and the password
 * below; proxy Vite on 5174 using API_PROXY_TARGET. External model discovery
 * alone is mocked; saving, roles, keys, users, agent controls and auth use real APIs.
 */
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const BASE = process.env.UI_URL || 'http://localhost:5174'
assert(new URL(BASE).hostname === 'localhost', 'Destructive regression restricted to localhost')
const PASSWORD = 'test-owner-password-for-ui-only'

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/tmp/chromium', args: ['--no-sandbox'] })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const go = async (section) => { await page.goto(BASE + '/#settings/' + section); await page.locator('.a-admin').waitFor(); await page.locator('.a-admin [aria-label="Loading settings"]').waitFor({ state: 'hidden' }) }
  const toast = async (text) => { await page.locator('.toast-stack').getByText(text, { exact: false }).last().waitFor() }
  await page.goto(BASE + '/#settings/diagnostics')
  await page.getByLabel('Workspace password').fill(PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Run diagnostics' }).click()
  await toast('Diagnostics completed.')
  await page.getByPlaceholder('Search logs…').fill('no-such-log')
  await page.getByText('No matching events').waitFor()
  await page.getByRole('button', { name: 'Refresh logs', exact: true }).click()
  await page.getByLabel('Filter log level').selectOption('error')

  await go('runtimes')
  const agent = page.locator('.a-card').filter({ has: page.getByRole('heading', { name: 'NORA', exact: true }) })
  await agent.getByRole('button', { name: 'Stop agent', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click()
  await agent.getByRole('button', { name: 'Stop agent', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Stop agent', exact: true }).click()
  await agent.getByRole('button', { name: 'Start agent', exact: true }).click()
  await toast('NORA enabled for new tasks')
  await page.getByPlaceholder('Search agents…').fill('none')
  await page.getByRole('button', { name: 'Clear search' }).click()

  await page.route('**/api/providers/*/models', async (route) => {
    await route.fulfill({ json: { valid: true, models: [
      { id: 'test-reasoning-32b:free', free: true, size: 20000000000 },
      { id: 'test-coder-3b:free', free: true, size: 2000000000 },
      { id: 'test-vision-pro', free: false, size: 10000000000 },
    ] } })
  })
  await go('connections')
  for (const card of await page.locator('.a-provider').all()) {
    const password = card.locator('input[type=password]')
    if (await password.count()) await password.fill('test-only-provider-key-never-production')
    await card.getByRole('button', { name: 'Test connection', exact: true }).click()
    await card.getByText('Connected', { exact: true }).waitFor()
    const select = card.locator('select').filter({ has: page.locator('option[value="test-coder-3b:free"]') })
    await select.selectOption('')
    assert(await card.getByRole('button', { name: 'Save & use model', exact: true }).isDisabled())
    await card.getByLabel('Optimize for', { exact: true }).selectOption('code')
    await card.getByRole('button', { name: 'Auto-select best model', exact: true }).click()
    await card.getByRole('button', { name: 'Save & use model', exact: true }).click()
    await toast('Connection and default model saved.')
  }
  const saved = await (await page.request.get(BASE + '/api/providers')).json()
  assert(saved.every((p) => p.model === 'test-coder-3b:free'))

  await go('access')
  await page.getByRole('button', { name: 'Create key', exact: true }).click()
  const dialog = page.getByRole('dialog')
  assert(await dialog.getByRole('button', { name: 'Create key', exact: true }).isDisabled())
  await dialog.getByLabel('Key name').fill('Browser regression key')
  await dialog.getByRole('button', { name: 'Create key', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Copy key', exact: true }).click()
  await toast('Copied to clipboard.')
  const token = await page.evaluate(() => navigator.clipboard.readText())
  assert(token.startsWith('ao_'))
  await page.getByRole('dialog').getByRole('button', { name: 'Done' }).click()
  await page.getByLabel('Regenerate Browser regression key', { exact: true }).first().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Regenerate key', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Done' }).click()
  await page.getByLabel('Revoke Browser regression key', { exact: true }).first().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Revoke access', exact: true }).click()
  await toast('API key revoked.')

  await go('instance')
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await toast('Instance details refreshed.')
  await page.getByRole('button', { name: 'Manage deployment', exact: true }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)

  await go('appearance')
  for (const label of ['Light', 'Dark', 'Blue', 'Indigo', 'Compact', 'Comfortable']) await page.getByRole('button', { name: label, exact: true }).click()
  assert.equal(await page.locator('html').getAttribute('class'), 'theme-dark')
  await page.getByRole('button', { name: 'night', exact: true }).click()
  await page.getByRole('button', { name: 'day', exact: true }).click()
  await toast('Office lighting updated.')

  await go('account')
  await page.getByLabel('Full name', { exact: true }).fill('UI Test Owner')
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await toast('Profile updated.')

  await go('users')
  await page.getByRole('button', { name: 'Invite member', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Full name').fill('Regression Member')
  await page.getByRole('dialog').getByLabel('Email address').fill('browser-regression@example.test')
  await page.getByRole('dialog').getByRole('button', { name: 'Create invitation' }).click()
  const link = await page.getByRole('dialog').locator('code').textContent()
  assert(link.includes('#invite='))
  await page.getByRole('dialog').getByRole('button', { name: 'Copy invitation link' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Done' }).click()
  const invitePage = await context.newPage()
  await invitePage.goto(link)
  await invitePage.getByLabel('New password').fill('test-invitation-member-password')
  await invitePage.getByRole('button', { name: 'Accept invitation', exact: true }).click()
  await invitePage.close()
  await go('users')
  await page.getByLabel('Change role for Regression Member').click()
  await page.getByRole('dialog').getByLabel('Role').selectOption('Editor')
  await page.getByRole('dialog').getByRole('button', { name: 'Save role', exact: true }).click()
  await toast('Role updated.')
  await page.getByPlaceholder('Search members…').fill('none')
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.getByLabel('Delete Regression Member', { exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click()
  await page.getByLabel('Delete Regression Member', { exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete user', exact: true }).click()
  await toast('User removed.')

  await go('roles')
  await page.getByRole('tab', { name: 'Viewer', exact: true }).click()
  const permission = page.getByLabel('Viewer projects write', { exact: true })
  await permission.check()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  assert(!(await permission.isChecked()))
  await permission.check()
  await page.getByRole('button', { name: 'Save permissions', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Save permissions', exact: true }).click()
  await toast('Role permissions saved and enforced.')
  await permission.uncheck()
  await page.getByRole('button', { name: 'Save permissions', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Save permissions', exact: true }).click()

  await page.getByLabel('Collapse sidebar').click()
  await page.waitForFunction(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 64)
  await page.getByLabel('Expand sidebar').click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Open navigation', { exact: true }).click()
  await page.locator('.sidebar').getByRole('link', { name: 'Diagnostics', exact: true }).click()
  await page.getByRole('heading', { name: 'Diagnostics', exact: true }).waitFor()
  await page.getByLabel('Open navigation', { exact: true }).click()
  await page.keyboard.press('Escape')
  assert(!(await page.locator('.sidebar').evaluate((e) => e.classList.contains('drawer-open'))))

  await go('account')
  await page.getByLabel('Current password', { exact: true }).fill(PASSWORD)
  await page.getByLabel('New password', { exact: true }).fill('replacement-ui-password-only')
  await page.getByLabel('Confirm new password', { exact: true }).fill('replacement-ui-password-only')
  await page.getByRole('button', { name: 'Update password', exact: true }).click()
  await page.getByRole('heading', { name: 'Welcome back' }).waitFor()
  await page.getByLabel('Workspace password').fill('replacement-ui-password-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.locator('.a-admin').waitFor()
  // Restore test credentials for repeatability.
  await page.request.post(BASE + '/api/admin/me/password', { data: { current_password: 'replacement-ui-password-only', new_password: PASSWORD } })
  assert.deepEqual(errors, [])
  await browser.close()
  console.log('PASS: admin page actions, real persistence/auth, provider discovery fixtures + real model saves, keys/copy/rotation/revoke, invitations/roles/delete, profile/password, themes/density, sidebar/drawer/Escape')
}
main().catch((e) => { console.error(e); process.exit(1) })
