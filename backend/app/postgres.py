"""Small psycopg adapter preserving the existing SQLite helper/row interface.

Supabase uses isolated, non-PostgREST schemas; only the gated Python API can
access these single-owner tables. SQLite remains the local/test default.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

SCHEMAS = {'agency_office', 'agency_sitebuilder'}


def qmark_sql(statement: str) -> str:
    """Translate bind markers outside SQL strings/comments, never interpolate values."""
    statement = statement.replace('%', '%%')
    output, i, quote, comment = [], 0, None, False
    while i < len(statement):
        c = statement[i]
        if comment:
            output.append(c)
            if c == '\n': comment = False
        elif quote:
            output.append(c)
            if c == quote:
                if i + 1 < len(statement) and statement[i + 1] == quote:
                    output.append(statement[i + 1]); i += 1
                else: quote = None
        elif statement[i:i+2] == '--':
            output.append('--'); i += 1; comment = True
        elif c in ("'", '"'):
            quote = c; output.append(c)
        elif c == '?': output.append('%s')
        else: output.append(c)
        i += 1
    # psycopg placeholders require literal percent signs to be doubled, including
    # inside SQL strings (bound parameter contents are never modified).
    return ''.join(output)


def postgres_schema(script: str) -> str:
    script = re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', script, flags=re.I)
    script = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', script, flags=re.I)
    script = re.sub(r'\bBLOB\b', 'BYTEA', script, flags=re.I)
    return script.replace('CREATE TABLE IF NOT EXISTS agents (', 'CREATE TABLE IF NOT EXISTS agents (rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,')


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int): return tuple(self.values())[key]
        return super().__getitem__(key)


class Result:
    def __init__(self, cursor):
        self.rowcount = cursor.rowcount
        self.rows = [Row(row) for row in cursor.fetchall()] if cursor.description else []
        self.position = 0

    def fetchone(self):
        if self.position >= len(self.rows): return None
        row = self.rows[self.position]; self.position += 1
        return row

    def fetchall(self):
        rows = self.rows[self.position:]; self.position = len(self.rows)
        return rows

    def __iter__(self): return iter(self.fetchall())


class Connection:
    def __init__(self, schema: str, *, transactional=False):
        if schema not in SCHEMAS: raise ValueError('Unknown database schema')
        import psycopg
        from psycopg.rows import dict_row
        self.schema, self.transactional = schema, transactional
        from psycopg.conninfo import conninfo_to_dict
        options = conninfo_to_dict(os.environ['DATABASE_URL'])
        if (options.get('host', '').endswith('.pooler.supabase.com')
                and options.get('sslrootcert', 'system') == 'system'):
            # Supabase's shared pooler uses its public private-root CA, not the
            # OS trust store. Keep chain AND hostname verification enabled.
            options.update(sslmode='verify-full', sslrootcert=str(
                Path(__file__).resolve().parents[1] / 'certs' / 'supabase-root-2021.crt'))
        self.raw = psycopg.connect(**options, connect_timeout=10,
            prepare_threshold=None, autocommit=not transactional, row_factory=dict_row)

    @property
    def closed(self): return self.raw.closed

    def _scope(self):
        # Schema is selected from a fixed allowlist, not user input. SET LOCAL is
        # necessary with Supavisor transaction pooling; session SET is unsafe.
        self.raw.execute(f'SET LOCAL search_path TO {self.schema}, pg_catalog')
        self.raw.execute("SET LOCAL statement_timeout TO '260s'")

    def execute(self, statement, args=()):
        if self.transactional:
            self._scope()
            return Result(self.raw.execute(qmark_sql(statement), tuple(args)))
        with self.raw.transaction():
            self._scope()
            return Result(self.raw.execute(qmark_sql(statement), tuple(args)))

    def executescript(self, script):
        def run():
            self._scope()
            self.raw.execute('SELECT pg_advisory_xact_lock(hashtext(%s))', (self.schema + '_schema',))
            # Schema constants contain no semicolons in literals. Do not accept
            # user-supplied scripts; regular queries always use bound parameters.
            script_sql = postgres_schema(script)
            self.raw.execute(script_sql, prepare=False)
        if self.transactional: run()
        else:
            with self.raw.transaction(): run()

    def commit(self):
        if self.transactional: self.raw.commit()

    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()
    def __enter__(self): return self
    def __exit__(self, kind, error, traceback):
        try:
            if kind: self.raw.rollback()
            else: self.raw.commit()
        finally: self.raw.close()
