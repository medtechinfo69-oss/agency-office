# Meta Graph API — DRAFT / APPROVAL ONLY
# --------------------------------------------------------------------------
def meta_configured() -> bool:
    return bool(settings.meta_token and settings.meta_page_id)


def create_meta_draft(project_id: str, payload: dict) -> dict:
    """Store a draft locally. No network call happens at this stage."""
    did = db.new_id("mdraft")
    db.execute(
        "INSERT INTO meta_drafts (id, project_id, payload, status, created_at, updated_at) "
        "VALUES (?,?,?,'draft',?,?)",
        (did, project_id, db.jdump(payload), db.now(), db.now()))
    return {"id": did, "status": "draft"}


async def publish_meta_draft(draft_id: str) -> dict:
    """Called ONLY after the Boss clicks Approve. Requires .env Meta tokens."""
    row = db.one("SELECT * FROM meta_drafts WHERE id=?", (draft_id,))
    if not row:
        raise ValueError("draft not found")
    if not meta_configured():
        db.execute("UPDATE meta_drafts SET status='failed', error=?, updated_at=? WHERE id=?",
                   ("Meta API not configured — set META_ACCESS_TOKEN and META_PAGE_ID in .env",
                    db.now(), draft_id))
        raise RuntimeError(
            "Meta Graph API is not configured. Set META_ACCESS_TOKEN, META_PAGE_ID "
            "(and META_IG_BUSINESS_ID for Instagram) in .env, or export the ZIP instead.")
    payload = db.jload(row["payload"], {})
    message = payload.get("caption") or payload.get("primary_text", "")
    link = payload.get("link", "")
    try:
        async with httpx.AsyncClient(timeout=30) as client:
            r = await client.post(
                f"https://graph.facebook.com/v21.0/{settings.meta_page_id}/feed",
                data={"message": message, "link": link, "published": "false",
                      "access_token": settings.meta_token})
            data = r.json()
            if "error" in data:
                raise RuntimeError(data["error"].get("message", "Meta API error"))
            eid = data.get("id", "")
        db.execute("UPDATE meta_drafts SET status='published', external_id=?, updated_at=? WHERE id=?",
                   (eid, db.now(), draft_id))
        return {"status": "published", "external_id": eid}
    except httpx.HTTPError as e:
        db.execute("UPDATE meta_drafts SET status='failed', error=?, updated_at=? WHERE id=?",
                   (str(e), db.now(), draft_id))
        raise


def list_meta_drafts(project_id: str) -> list[dict]:
    rows = db.query("SELECT * FROM meta_drafts WHERE project_id=? ORDER BY created_at DESC", (project_id,))
    out = []
    for r in rows:
        d = dict(r)
        d["payload"] = db.jload(d["payload"], {})
        out.append(d)
    return out
