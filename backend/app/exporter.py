"""Export: ZIP package with images + captions + calendar CSV.

Also provides Meta Graph API draft publishing (approval-gated: nothing is
published until the Boss clicks Approve; disabled unless .env is configured).
"""
from __future__ import annotations

import csv
import io
import json
import os
import zipfile
from pathlib import Path
from typing import Optional

import httpx

from . import db
from .config import settings


def project_export_zip(project_id: str) -> Path:
    proj = db.one("SELECT * FROM projects WHERE id=?", (project_id,))
    if not proj:
        raise ValueError("project not found")
    deliverables = [dict(r) for r in db.query(
        "SELECT * FROM deliverables WHERE project_id=? ORDER BY created_at", (project_id,))]
    for d in deliverables:
        d["data"] = db.jload(d["data"], {})

    out = settings.export_dir / f"{project_id}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        # README
        readme = [
            f"# {proj['name']} — delivery package",
            f"Status: {proj['status']}   Progress: {proj['progress']}%",
            f"Generated by AGENCY OFFICE",
            "", "Contents:", "- campaign.json / calendar / copy deliverables",
            "- captions.txt", "- calendar.csv", "- images/ (all generated creatives)",
        ]
        z.writestr("README.md", "\n".join(readme))

        # deliverable JSONs
        for i, d in enumerate(deliverables):
            z.writestr(f"deliverables/{i:02d}_{d['kind']}_{_slug(d['title'])}.json",
                       json.dumps(d["data"], ensure_ascii=False, indent=2))

        # captions.txt from calendar / campaign
        captions = _captions_text(deliverables)
        if captions:
            z.writestr("captions.txt", captions)

        # calendar.csv
        cal = next((d["data"] for d in deliverables
                    if d["kind"] == "calendar" or "days" in d.get("data", {})), None)
        if cal and isinstance(cal, dict) and cal.get("days"):
            buf = io.StringIO()
            w = csv.writer(buf)
            w.writerow(["day", "channel", "format", "theme", "caption", "hashtags", "best_time"])
            for day in cal["days"]:
                w.writerow([day.get("day"), day.get("channel"), day.get("format"),
                            day.get("theme"), day.get("caption"),
                            " ".join(day.get("hashtags", [])), day.get("best_time")])
            z.writestr("calendar.csv", buf.getvalue())

        # images referenced anywhere in deliverables (and media dir)
        media = settings.media_dir / project_id
        seen = set()
        if os.getenv('DATABASE_URL'):
            for item in db.query('SELECT path, data FROM media_files WHERE path LIKE ?', (project_id + '/%',)):
                name = Path(item['path']).name
                if Path(name).suffix.lower() in ('.png', '.jpg', '.jpeg', '.svg', '.webp'):
                    z.writestr(f'images/{name}', bytes(item['data']))
                    seen.add(name)
        if media.exists():
            for p in sorted(media.rglob("*")):
                if p.is_file() and p.name not in seen and p.suffix.lower() in (".png", ".jpg", ".jpeg", ".svg", ".webp"):
                    z.write(p, f"images/{p.name}")
                    seen.add(p.name)

        # meta drafts (approval records)
        drafts = [dict(r) for r in db.query("SELECT * FROM meta_drafts WHERE project_id=?", (project_id,))]
        for d in drafts:
            d["payload"] = db.jload(d["payload"], {})
        if drafts:
            z.writestr("meta_drafts.json", json.dumps(drafts, ensure_ascii=False, indent=2))

    return out


def _slug(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in s.lower())[:30]


def _captions_text(deliverables: list[dict]) -> str:
    lines: list[str] = []
    for d in deliverables:
        data = d.get("data") or {}
        if isinstance(data, dict) and data.get("days"):
            lines.append(f"== {d['title']} ==")
            for day in data["days"]:
                lines.append(f"Day {day.get('day')} [{day.get('channel')}/{day.get('format')}] "
                             f"{day.get('best_time','')}\n{day.get('caption','')}\n"
                             f"{' '.join(day.get('hashtags', []))}\n")
        if isinstance(data, dict) and data.get("variants"):
            lines.append(f"== {d['title']} ==")
            for v in data["variants"]:
                lines.append(f"[{v.get('label')}] {v.get('headline')}\n{v.get('primary_text')}\n"
                             f"CTA: {v.get('cta')}  {v.get('utm','')}\n")
        if isinstance(data, dict) and data.get("items"):
            lines.append(f"== {d['title']} ==")
            for it in data["items"]:
                if isinstance(it, dict) and it.get("text"):
                    lines.append(f"- ({it.get('type','copy')}) {it['text']}")
    return "\n".join(lines)


